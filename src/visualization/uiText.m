function s = uiText(fmt, varargin)
%UITEXT Interface text in the current language (English / Turkish).
%
%   S = UITEXT(FMT, ARGS...) translates the English text or sprintf format
%   FMT into the current language and fills in ARGS (MATLAB positional
%   identifiers such as %2$s let a translation reorder them). Text without
%   a translation is returned in English, so a missing entry is visible
%   but never breaks the interface.
%   UITEXT("--lang", "tr" | "en") sets the language (default "en");
%   UITEXT("--lang") returns it.
%   Nouns and bin words (hosts, flows, minute, ...) are translated with the
%   same call; Turkish uses the singular after numbers ("490 akış").
%
%   Scope: the application and the plotting functions. The evidence text
%   generated by explainAnomalies is stored in the analysis bundle in
%   English.

persistent lang dict
if isempty(lang)
    lang = "en";
end
fmt = string(fmt);
if fmt == "--lang"
    if nargin > 1
        lang = lower(string(varargin{1}));
    end
    s = lang;
    return;
end
if lang == "tr"
    if isempty(dict)
        dict = turkish();
    end
    if isKey(dict, char(fmt))
        fmt = string(dict(char(fmt)));
    end
end
if isempty(varargin)
    s = fmt;
else
    s = string(sprintf(fmt, varargin{:}));
end
end

