function s = uiText(fmt, varargin)
%UITEXT Interface text in the current language (English / Turkish).
%
%   S = UITEXT(FMT, ARGS...) translates the English text or sprintf format
%   FMT into the current language and fills in ARGS (MATLAB positional
%   identifiers such as %2$s let a translation reorder them). Text without
%   a translation is returned in English, so a missing entry is visible
%   but never breaks the interface.
%   UITEXT("--lang", "tr" | "en") sets the language (default "tr");
%   UITEXT("--lang") returns it. Invalid languages raise an error.
%   UITEXT("--format", LANG, FMT, ARGS...) formats without changing the
%   selected language, for deterministic saved evidence and tests.
%   Nouns and bin words (hosts, flows, minute, ...) are translated with the
%   same call; Turkish uses the singular after numbers ("490 akış").
%
%   Scope: the application and the plotting functions. The evidence text
%   generated by explainAnomalies is stored in the analysis bundle in
%   English.

persistent lang dict headers
if isempty(lang)
    lang = "tr";
end
fmt = textScalar(fmt);
if fmt == "--lang"
    if numel(varargin) > 1
        error("MOSAIC:UiTextArguments", "--lang accepts at most one language.");
    end
    if ~isempty(varargin)
        lang = checkedLanguage(varargin{1});
    end
    s = lang;
    return;
end
selected = lang;
if fmt == "--format"
    if numel(varargin) < 2
        error("MOSAIC:UiTextArguments", "--format requires a language and text key.");
    end
    selected = checkedLanguage(varargin{1});
    fmt = textScalar(varargin{2});
    varargin = varargin(3:end);
end
if selected == "tr"
    if isempty(dict)
        dict = turkish();
    end
    if isKey(dict, char(fmt))
        fmt = string(dict(char(fmt)));
    end
end
if selected == "en"
    if isempty(headers)
        headers = englishTableHeaders();
    end
    if isKey(headers, char(fmt))
        fmt = string(headers(char(fmt)));
    end
end
if isempty(varargin)
    s = fmt;
else
    s = string(sprintf(fmt, varargin{:}));
end
end

function s = textScalar(value)
s = string(value);
if ~isscalar(s) || ismissing(s)
    error("MOSAIC:UiTextArguments", "Text keys must be nonmissing scalar text.");
end
end

function lang = checkedLanguage(value)
lang = lower(textScalar(value));
if ~ismember(lang, ["tr", "en"])
    error("MOSAIC:UnsupportedLanguage", "Supported languages are tr and en.");
end
end

