function P = networkFlowProfiles()
%NETWORKFLOWPROFILES Known network-traffic dataset layouts (docs/NETWORK_DATASETS.md).
%
%   P = NETWORKFLOWPROFILES() returns a struct array, one element per
%   supported public dataset. inspectDatasetFile matches a file against
%   them; importNetworkFlows reads a file with one of them. Fields:
%     id, name        identifier and display name
%     signature       normalized column names that must ALL be present
%                     (headered files); empty for headerless layouts
%     positional      column names for HEADERLESS files (in file order);
%                     empty for headered layouts
%     content_checks  for positional layouts: struct array (column, kind)
%                     verified on the first rows before the profile is
%                     accepted ("ipv4", "integer", "binary", "number",
%                     "success_fail"), so a wrong guess fails loudly
%     map             struct of role -> column name(s). Roles: time, src,
%                     dst, sport, dport, proto, duration, bytes, packets,
%                     state, outcome, label, label_detail. A string array
%                     means "sum these columns" (bytes, packets). "" = absent
%     time_unit       parseTimeColumn unit for numeric time columns
%     time_formats    text formats tried first for text time columns
%     duration_scale  multiply the duration column by this to get seconds
%     label_rule      "ctu13" | "benign_word" | "binary" | "none"
%                     (see labelNetworkFlows)
%     source          official page (licence and download terms there)
%     verified        how the layout was checked (read this before trusting
%                     an import: the platform never guesses silently)
%
%   Column names are compared after normalization (lower case, spaces,
%   underscores and other punctuation removed), because published copies
%   of the same dataset differ in case and leading spaces.

P = struct('id', {}, 'name', {}, 'signature', {}, 'positional', {}, ...
    'content_checks', {}, 'map', {}, 'time_unit', {}, 'time_formats', {}, ...
    'duration_scale', {}, 'label_rule', {}, 'source', {}, 'verified', {});

% --- CTU-13 (Argus bidirectional flows, .binetflow) ---------------------------
P(end+1) = profile("ctu13_binetflow", "CTU-13 botnet flows (Argus binetflow)", ...
    ["starttime","dur","proto","srcaddr","sport","dir","dstaddr","dport", ...
    "state","totpkts","totbytes","label"], strings(1,0), [], ...
    roles("StartTime", "SrcAddr", "DstAddr", "Sport", "Dport", "Proto", "Dur", ...
    "TotBytes", "TotPkts", "State", "", "Label", ""), ...
    "auto", "yyyy/MM/dd HH:mm:ss.SSSSSS", 1, "ctu13", ...
    "https://stratosphereips.org/datasets-ctu13 (CC BY)", ...
    "Header verified on Stratosphere's published binetflow samples " + ...
    "(comma- and tab-separated variants); label vocabulary from the dataset page.");

% --- CIC-IDS2017 (CICFlowMeter labelled flows with IPs) -------------------------
% Only the GeneratedLabelledFlows CSVs carry IPs and timestamps; the
% MachineLearningCSV files do not and cannot be analysed as a network.
P(end+1) = profile("cicids2017_flows", "CIC-IDS2017 labelled flows (CICFlowMeter)", ...
    ["sourceip","destinationip","timestamp","label"], strings(1,0), [], ...
    roles("Timestamp", "Source IP", "Destination IP", "Source Port", ...
    "Destination Port", "Protocol", "Flow Duration", ...
    ["Total Length of Fwd Packets", "Total Length of Bwd Packets"], ...
    ["Total Fwd Packets", "Total Backward Packets"], "", "", "Label", ""), ...
    "auto", ["dd/MM/yyyy HH:mm:ss", "d/M/yyyy H:mm:ss", "d/M/yyyy H:mm"], 1e-6, ...
    "benign_word", "https://www.unb.ca/cic/datasets/ids-2017.html", ...
    "Column names from the dataset description and CICFlowMeter documentation; " + ...
    "NOT verified on a downloaded file in this repository. Flow Duration is " + ...
    "documented in microseconds. Known issues (Lanvin et al. 2022): label errors, " + ...
    "duplicated features, 12-hour timestamps without AM/PM in some files.");

% --- UNSW-NB15 (full records with IPs) ------------------------------------------
unswCols = ["srcip","sport","dstip","dsport","proto","state","dur","sbytes", ...
    "dbytes","sttl","dttl","sloss","dloss","service","Sload","Dload","Spkts", ...
    "Dpkts","swin","dwin","stcpb","dtcpb","smeansz","dmeansz","trans_depth", ...
    "res_bdy_len","Sjit","Djit","Stime","Ltime","Sintpkt","Dintpkt","tcprtt", ...
    "synack","ackdat","is_sm_ips_ports","ct_state_ttl","ct_flw_http_mthd", ...
    "is_ftp_login","ct_ftp_cmd","ct_srv_src","ct_srv_dst","ct_dst_ltm", ...
    "ct_src_ltm","ct_src_dport_ltm","ct_dst_sport_ltm","ct_dst_src_ltm", ...
    "attack_cat","Label"];
unswMap = roles("Stime", "srcip", "dstip", "sport", "dsport", "proto", "dur", ...
    ["sbytes", "dbytes"], ["Spkts", "Dpkts"], "state", "", "Label", "attack_cat");
unswSource = "https://research.unsw.edu.au/projects/unsw-nb15-dataset";
P(end+1) = profile("unsw_nb15", "UNSW-NB15 records (with header)", ...
    ["srcip","dstip","stime","label"], strings(1,0), [], unswMap, ...
    "posix_s", strings(1,0), 1, "binary", unswSource, ...
    "Column names from UNSW-NB15_features.csv as published; NOT verified on a " + ...
    "downloaded file in this repository.");
P(end+1) = profile("unsw_nb15_raw", "UNSW-NB15 records UNSW-NB15_1..4.csv (no header)", ...
    strings(1,0), unswCols, ...
    struct('column', {"srcip", "dstip", "Stime", "Label"}, ...
    'kind', {"ipv4", "ipv4", "integer", "binary"}), unswMap, ...
    "posix_s", strings(1,0), 1, "binary", unswSource, ...
    "Column order from the published feature list (49 columns); NOT verified " + ...
    "on a downloaded file. Content checks (IPv4, integer Stime, 0/1 label) " + ...
    "must pass before the profile is used. The train/test split files have " + ...
    "no IP columns and cannot be analysed as a network.");

% --- LANL Comprehensive Multi-Source Cyber-Security Events -------------------
P(end+1) = profile("lanl_auth", "LANL auth.txt (authentication events, no header)", ...
    strings(1,0), ["time","src_user","dst_user","src_computer","dst_computer", ...
    "auth_type","logon_type","auth_orientation","outcome"], ...
    struct('column', {"time", "outcome"}, 'kind', {"integer", "success_fail"}), ...
    roles("time", "src_computer", "dst_computer", "", "", "auth_type", "", "", ...
    "", "", "outcome", "", ""), "posix_s", strings(1,0), 1, "none", ...
    "https://csr.lanl.gov/data/cyber1/", ...
    "Field order as documented by LANL and repeated in the papers using the " + ...
    "data; NOT verified on a downloaded file. Times are seconds from an " + ...
    "undisclosed origin (epoch 1): only relative timing is meaningful. " + ...
    "Red-team labels come from redteam.txt (opts.labels_file).");
P(end+1) = profile("lanl_flows", "LANL flows.txt (network flows, no header)", ...
    strings(1,0), ["time","duration","src_computer","src_port","dst_computer", ...
    "dst_port","protocol","packets","bytes"], ...
    struct('column', {"time", "duration", "packets", "bytes"}, ...
    'kind', {"integer", "number", "number", "number"}), ...
    roles("time", "src_computer", "dst_computer", "src_port", "dst_port", ...
    "protocol", "duration", "bytes", "packets", "", "", "", ""), ...
    "posix_s", strings(1,0), 1, "none", "https://csr.lanl.gov/data/cyber1/", ...
    "Field order from the LANL description; NOT verified on a downloaded file. " + ...
    "Relative times as in auth.txt; no labels in this file.");
end

function p = profile(id, name, signature, positional, checks, map, timeUnit, ...
    timeFormats, durationScale, labelRule, source, verified)
if isempty(checks)
    checks = struct('column', {}, 'kind', {});
end
p = struct('id', id, 'name', name, 'signature', signature, ...
    'positional', positional, 'content_checks', checks, 'map', map, ...
    'time_unit', timeUnit, 'time_formats', timeFormats, ...
    'duration_scale', durationScale, 'label_rule', labelRule, ...
    'source', source, 'verified', verified);
end

function m = roles(time, src, dst, sport, dport, proto, duration, bytes, ...
    packets, state, outcome, label, labelDetail)
m = struct('time', time, 'src', src, 'dst', dst, 'sport', sport, ...
    'dport', dport, 'proto', proto, 'duration', duration);
m.bytes = bytes;          % may be a string array (summed)
m.packets = packets;
m.state = state;
m.outcome = outcome;
m.label = label;
m.label_detail = labelDetail;
end
